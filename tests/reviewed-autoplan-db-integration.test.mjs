import test from 'node:test';
import assert from 'node:assert/strict';
import {Readable} from 'node:stream';
import {createHash,randomUUID} from 'node:crypto';
import pg from 'pg';
import {createApi} from '../api/index.mjs';
const db=process.env.CIVOLTEN_TEST_DATABASE_URL;
if(!db||!/^postgres(?:ql)?:\/\/postgres:[^@]+@(?:127\.0\.0\.1|localhost):5432\/civolten_test(?:\?.*)?$/.test(db)){
 test.skip('Autoplan only tests disposable localhost PostgreSQL',()=>{});
}else{
 const pool=new pg.Pool({connectionString:db,max:2});
 const sql={async query(query,args=[]){return (await pool.query(query,args)).rows}};
 const handler=createApi(sql);
 async function request(token,route,method='GET',payload){
  const req=Readable.from(payload===undefined?[]:[Buffer.from(JSON.stringify(payload))]);
  req.url='/api/v1/'+route;req.method=method;
  req.headers={host:'localhost:3000',cookie:'civolten_dev_session='+token,
   ...(method==='GET'?{}:{'x-civolten-request':'1'}),
   ...(payload===undefined?{}:{'content-type':'application/json'})};
  const res={statusCode:200,setHeader(){},end(value){this.body=JSON.parse(value)}};
  await handler(req,res);
  return {status:res.statusCode,body:res.body};
 }
 test('Postgres: gera equipe e atividades UMA única vez, com horas revisadas e pessoal real', {timeout:30000},async()=>{
  const user=randomUUID(),client=randomUUID(),budget=randomUUID(),
   price=randomUUID(),version=randomUUID(),item=randomUUID(),token='a'.repeat(64);
  try{
   await sql.query("INSERT INTO app_users(id,login,password_hash,role,must_change_password) VALUES($1,$2,'qa-placeholder','administrador',false)",
    [user,'autoplan.qa.'+user+'@example.test']);
   await sql.query("INSERT INTO app_sessions(token_hash,user_id,expires_at) VALUES($1,$2,now()+interval '1 hour')",
    [createHash('sha256').update(token).digest('hex'),user]);
   await sql.query("INSERT INTO clients(id,name) VALUES($1,'Autoplan cliente QA isolado')",[client]);
   await sql.query("INSERT INTO budgets(id,code,client_id,title,reference_month,regime,bdi_pct,created_by) VALUES($1,$2,$3,'Autoplan QA','2025-09','Sem desoneração',0,$4)",
    [budget,'AUTOPLAN-'+budget.slice(0,8),client,user]);
   await sql.query("INSERT INTO reference_price_versions(id,source,reference_month,regime,scope,source_url,sha256) VALUES($1,'SIURB','2025-09','Sem desoneração','Edificações',$2,$3)",
    [version,'https://prefeitura.sp.gov.br/teste/'+price,price.replaceAll('-','')+price.replaceAll('-','')]);
   await sql.query("INSERT INTO reference_prices(id,version_id,code,description,unit,unit_cost) VALUES($1,$2,$3,'Serviço QA','UN',100)",
    [price,version,'QA-'+price.slice(0,8)]);
   await sql.query("INSERT INTO reference_composition_details(reference_price_id,labor,other,direct_hh_per_unit) VALUES($1,$2::jsonb,'[]'::jsonb,1.5)",
    [price,JSON.stringify([{code:'qa_autoplan_2099',name:'Servente QA',coef:1,unit:'H'},
      {code:'qa_autoplan_2020',name:'Pedreiro QA',coef:.5,unit:'H'}])]);
   await sql.query("INSERT INTO budget_items(id,budget_id,position,source_code,source_name,unit,quantity,direct_unit_cost,reference_price_id,direct_labor_hh_unit,labor_review_state) VALUES($1,$2,1,'QA-100','Serviço teste','UN',40,100,$3,1.5,'revisado')",
    [item,budget,price]);
   for(const [role,name] of [['qa_autoplan_2099','Servente QA'],['qa_autoplan_2099','Servente QA'],['qa_autoplan_2020','Pedreiro QA']]){
    await sql.query("INSERT INTO company_workers(display_name,role_code,role_name,monthly_employer_cost) VALUES($1,$2,$3,4000)",
     ['QA '+name+' '+randomUUID().slice(0,5),role,name]);
   }
   const params={lock_version:0,hours_day:'8',efficiency_pct:'80'};
   const path='budgets/'+budget+'/schedule-autogenerate';
   const first=await request(token,path,'POST',params);
   assert.equal(first.status,201,JSON.stringify(first.body));
   assert.equal(first.body.tasks_saved,1);
   assert.equal(first.body.roles_saved,2);
   assert.equal(first.body.employees_reserved,false);
   assert.equal(first.body.commercial_release,false);
   const actual=await sql.query('SELECT t.title,t.days_estimated,t.duration_review_state,t.start_on,t.budget_item_id,c.workday_hours,c.efficiency FROM schedule_tasks t JOIN crews c ON c.id=t.crew_id WHERE t.budget_id=$1',[budget]);
   assert.equal(actual.length,1);
   assert.equal(actual[0].duration_review_state,'pendente');
   assert.equal(Number(actual[0].days_estimated),4);
   assert.equal(actual[0].start_on,null);
   assert.equal(actual[0].budget_item_id,item);
   assert.equal((await request(token,path,'POST',params)).status,409);
   const count=await sql.query('SELECT count(*)::int AS n FROM schedule_tasks WHERE budget_id=$1',[budget]);
   assert.equal(count[0].n,1);
   const audits=await sql.query("SELECT count(*)::int AS n FROM audit_events WHERE actor_id=$1 AND action='autogenerated_draft'",[user]);
   assert.equal(audits[0].n,1);
  }finally{await pool.end()}
 });
}
