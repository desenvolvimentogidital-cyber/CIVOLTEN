/* CIVOLTEN — persist a draft schedule in one atomic PostgreSQL statement.
 * Uses REAL active company staff by SIURB role; no fictitious employees,
 * invented start dates, contract acceptance or silent approvals.
 */
import {randomUUID} from 'node:crypto';
import {buildReviewedAutoplan} from './reviewed-autoplan.mjs';
const uuid=x=>typeof x==='string'&&/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(x);
export async function handleReviewedAutoplan({req,res,sql,user,parts,method,send,readBody}){
 if(parts[0]!=='budgets'||parts[2]!=='schedule-autogenerate')return false;
 const done=(status,data)=>{send(res,status,data);return true};
 if(parts.length!==3||!uuid(parts[1]))return done(400,{error:'Orçamento inválido'});
 if(method!=='POST')return done(405,{error:'Geração do cronograma-base exige POST'});
 if(!['administrador','orcamentista'].includes(user?.role))
  return done(403,{error:'Somente equipe autorizada pode gerar planejamento-base'});
 const id=parts[1],body=await readBody(req);
 const version=body?.lock_version;
 if(!Number.isSafeInteger(version)||version<0)return done(400,{error:'Versão do orçamento obrigatória'});
 const budgets=await sql.query('SELECT id,status,lock_version,reference_month,regime FROM budgets WHERE id=$1 LIMIT 1',[id]);
 if(!budgets.length)return done(404,{error:'Orçamento não encontrado'});
 if(budgets[0].status!=='rascunho')return done(409,{error:'Somente orçamento em rascunho pode gerar cronograma-base'});
 if(Number(budgets[0].lock_version)!==version)return done(409,{error:'Orçamento atualizado por outro usuário; recarregue'});
 const existing=await sql.query(`SELECT
 (SELECT COUNT(*)::int FROM crews WHERE budget_id=$1 AND archived_at IS NULL) AS crews,
 (SELECT COUNT(*)::int FROM schedule_tasks WHERE budget_id=$1 AND archived_at IS NULL) AS tasks,
 (SELECT COUNT(*)::int FROM schedule_progress_measurements WHERE budget_id=$1) AS measurements`,[id]);
 if(Number(existing[0].crews)||Number(existing[0].tasks)||Number(existing[0].measurements))
  return done(409,{error:'Planejamento ou medições já existem; não sobrescrever o trabalho registrado'});
 const [items,workers]=await Promise.all([
  sql.query(`SELECT i.id,i.position,i.source_code,i.source_name,i.quantity,
    i.direct_labor_hh_unit,i.labor_review_state,i.reference_price_id,d.labor,
    (v.source='SIURB' AND v.reference_month=b.reference_month AND v.regime=b.regime) AS source_matches_budget
    FROM budget_items i JOIN budgets b ON b.id=i.budget_id
    LEFT JOIN reference_prices p ON p.id=i.reference_price_id
    LEFT JOIN reference_price_versions v ON v.id=p.version_id
    LEFT JOIN reference_composition_details d ON d.reference_price_id=i.reference_price_id
    WHERE i.budget_id=$1 AND i.deleted_at IS NULL ORDER BY i.position,i.id LIMIT 101`,[id]),
  sql.query('SELECT role_code,role_name,active FROM company_workers WHERE active=true ORDER BY role_code,id LIMIT 501',[])
 ]);
 if(workers.length>500)return done(409,{error:'Equipe acima do limite; revisar cadastro'});
 const plan=buildReviewedAutoplan({items,workers,hours_day:body.hours_day,efficiency_pct:body.efficiency_pct});
 if(!plan.ready)return done(409,{error:'Cronograma-base bloqueado por pendências reais',issues:plan.issues,requires_review:true});
 // One generated crew is a capacity template, NOT a reservation of its members.
 // The single-statement CTE protects all inserts with the original budget lock.
 const crewId=randomUUID();
 const statements=`WITH guarded AS (
 UPDATE budgets SET lock_version=lock_version+1,updated_at=now()
 WHERE id=$1 AND lock_version=$2 AND status='rascunho'
  AND NOT EXISTS(SELECT 1 FROM crews WHERE budget_id=$1 AND archived_at IS NULL)
  AND NOT EXISTS(SELECT 1 FROM schedule_tasks WHERE budget_id=$1 AND archived_at IS NULL)
  AND NOT EXISTS(SELECT 1 FROM schedule_progress_measurements WHERE budget_id=$1)
 RETURNING id
), crew AS (
 INSERT INTO crews(id,budget_id,title,workday_hours,efficiency)
 SELECT $3,guarded.id,'Equipe cadastrada - cronograma-base pendente',$4,$5 FROM guarded RETURNING id,budget_id
), roles AS (
 INSERT INTO crew_roles(id,crew_id,role_code,role_name,workers)
 SELECT gen_random_uuid(),crew.id,r.role_code,r.role_name,r.workers
 FROM crew CROSS JOIN jsonb_to_recordset($6::jsonb) AS r(role_code text,role_name text,workers integer)
 RETURNING id
), tasks AS (
 INSERT INTO schedule_tasks(id,budget_id,crew_id,budget_item_id,title,days_estimated,duration_review_state)
 SELECT gen_random_uuid(),crew.budget_id,crew.id,t.item_id,t.title,t.duration_workdays,'pendente'
 FROM crew CROSS JOIN jsonb_to_recordset($7::jsonb) AS t(item_id uuid,title text,duration_workdays integer)
 RETURNING id
), audited AS (
 INSERT INTO audit_events(actor_id,entity_type,entity_id,action,metadata)
 SELECT $8,'crews',crew.id,'autogenerated_draft',jsonb_build_object(
 'tasks',(SELECT count(*) FROM tasks),'roles',(SELECT count(*) FROM roles),
 'budget_lock_version',$2::integer,'efficiency',$5::numeric,'approved',false,
 'employee_assignment',false)
 FROM crew RETURNING id
)
SELECT crew.id AS crew_id,
 (SELECT count(*)::int FROM roles) AS roles_saved,
 (SELECT count(*)::int FROM tasks) AS tasks_saved
 FROM crew JOIN audited ON true`;
 const inserted=await sql.query(statements,[id,version,crewId,plan.hours_day,plan.efficiency,
  JSON.stringify(plan.roles),JSON.stringify(plan.tasks),user.id]);
 if(!inserted.length)return done(409,{error:'Concorrência detectada: recarregue o orçamento'});
 if(Number(inserted[0].tasks_saved)!==plan.tasks.length||Number(inserted[0].roles_saved)!==plan.roles.length)
  throw Error('Invariante de geração violada: total de tarefas/equipes não confere');
 return done(201,{created:true,crew_id:inserted[0].crew_id,tasks_saved:inserted[0].tasks_saved,
  roles_saved:inserted[0].roles_saved,needs_duration_review:true,
  employees_reserved:false,starts_execution:false,commercial_release:false,
  note:plan.notice});
}
